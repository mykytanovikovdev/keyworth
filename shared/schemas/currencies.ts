import { z } from "./zod.ts";

/*
 * The currencies Keyworth converts between. Fiat: every currency in use that
 * central banks publish a rate for, as Frankfurter lists them (161, checked on
 * 2026-11-07). Stablecoins: a trade's price can be in USDT or USDC, converted
 * at their own rate to the dollar, not as if they were one. A static list: it
 * changes rarely, and Settings shows it before anything is fetched.
 */

/** An ISO 4217 code: the shape, not a promise that a rate exists. */
export const currencyCodeSchema = z.string().regex(/^[A-Z]{3}$/);

export const STABLECOINS = ["USDT", "USDC"] as const;

/** What a trade's price can be in: a currency, or one of the stablecoins. */
export const priceCurrencySchema = z.union([
  currencyCodeSchema,
  z.enum(STABLECOINS),
]);

