// Regenerates worker/db/auth-schema.ts from the Better Auth configuration
// (`npm run db:auth-schema`). Run it after changing options that add tables or
// columns, then create a migration with `npm run db:generate`.
//
// Two adjustments to the CLI's output:
// - the CLI version is read from node_modules, so the generator always matches
//   the installed better-auth instead of whatever is newest on npm;
// - every timestamp becomes `timestamp with time zone`. Without a zone, the pg
//   driver writes dates in the machine's local zone while the Worker reads them
//   as UTC, so a session created from a laptop in UTC+4 would be off by hours.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const output = "worker/db/auth-schema.ts";
const { version } = JSON.parse(
  readFileSync(resolve(root, "node_modules/better-auth/package.json"), "utf8"),
) as { version: string };

execFileSync(
  "npx",
  [
    "--yes",
    `auth@${version}`,
    "generate",
    "--config",
    "worker/db/auth-cli.config.ts",
    "--adapter",
    "drizzle",
    "--dialect",
    "pg",
    "--output",
    output,
    "--yes",
  ],
  {
    cwd: root,
    stdio: "inherit",
    env: { ...process.env, BETTER_AUTH_TELEMETRY: "0" },
  },
);

const path = resolve(root, output);
const generated = readFileSync(path, "utf8");
const withZones = generated.replace(
  /timestamp\("(\w+)"\)/g,
  'timestamp("$1", { withTimezone: true })',
);
writeFileSync(
  path,
  `// Generated by \`npm run db:auth-schema\` from worker/auth.ts. Do not edit.\n${withZones}`,
);
execFileSync("npx", ["prettier", "--write", output], {
  cwd: root,
  stdio: "inherit",
});
